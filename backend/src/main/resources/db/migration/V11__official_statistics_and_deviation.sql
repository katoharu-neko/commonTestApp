DROP TABLE IF EXISTS averages;
DROP TABLE IF EXISTS score_records;

CREATE TABLE official_statistics (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    year INT NOT NULL,
    subject_id INT NOT NULL,
    category VARCHAR(50) NOT NULL,
    official_name VARCHAR(100) NOT NULL,
    full_score INT NOT NULL,
    candidates INT,
    average_score DECIMAL(6,2) NOT NULL,
    std_deviation DECIMAL(6,2) NOT NULL,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_official_statistics_year_subject (year, subject_id),
    CONSTRAINT fk_official_statistics_subject FOREIGN KEY (subject_id) REFERENCES subjects(id)
);

ALTER TABLE scores
    ADD COLUMN average_score DECIMAL(6,2) NULL,
    ADD COLUMN std_deviation DECIMAL(6,2) NULL,
    ADD COLUMN deviation_value DECIMAL(6,2) NULL;

